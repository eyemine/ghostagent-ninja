/**
 * authorship-declaration.ts
 *
 * Generates and signs an IP Authorship Declaration via EIP-712.
 *
 * Legal basis:
 * - Copyright Act 1968 (Cth) s.197 — written assignment by human author
 * - Electronic Transactions (Victoria) Act 2000 s.9 — electronic signature validity
 * - Human-as-Master-Author doctrine: AI agent is tool, human directs creative output
 *
 * The signed declaration is:
 * 1. Pinned to IPFS via Lighthouse (permanent record)
 * 2. Logged to GlassBox (immutable audit trail)
 * 3. Linked to the Story Protocol IPA via aiMetadata.socialLegal CID
 */

export const DECLARATION_VERSION = 'v1.0-2026-03-10';
export const CHAIN_ID = 100; // Gnosis Chain

// ── EIP-712 Domain ────────────────────────────────────────────────────────────

export const AUTHORSHIP_EIP712_DOMAIN = {
  name: 'GhostAgent IP Registry',
  version: '1',
  chainId: CHAIN_ID,
} as const;

// ── EIP-712 Types ─────────────────────────────────────────────────────────────

export const AUTHORSHIP_EIP712_TYPES = {
  AuthorshipDeclaration: [
    { name: 'authorWallet',    type: 'address' },
    { name: 'safeAddress',     type: 'address' },
    { name: 'agentTokenId',    type: 'uint256' },
    { name: 'declarationHash', type: 'bytes32' }, // SHA-256 of full declaration text
    { name: 'timestamp',       type: 'uint256' },
  ],
} as const;

// ── Params & Document interfaces ──────────────────────────────────────────────

export interface AuthorshipDeclarationParams {
  authorWallet: string;    // EOA or Safe owner address
  safeAddress: string;     // Gnosis Safe holding the agent NFT
  agentName: string;       // e.g. "ghostagent"
  domain: string;          // e.g. "nftmail.gno"
  agentTokenId: number;    // on-chain NFT token ID
  abn?: string;            // optional ABN if known
}

export interface AuthorshipDeclarationDocument {
  text: string;
  textHash: string;        // 0x-prefixed SHA-256 hex
  params: AuthorshipDeclarationParams;
  timestamp: number;
  version: string;
}

export interface AuthorshipDeclarationRecord {
  document: AuthorshipDeclarationDocument;
  signature: string;       // EIP-712 signature hex
  ipfsCid: string;         // ipfs://... of pinned JSON
  glassBoxCid?: string;
  storyPilCid?: string;    // Arweave/IPFS CID to attach to IPA socialLegal field
}

