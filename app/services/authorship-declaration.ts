// ── SHA-256 hash helper ────────────────────────────────────────────────────────

export async function hashText(text: string): Promise<string> {
  const encoder = new TextEncoder();
  const data = encoder.encode(text);
  const hashBuffer = await crypto.subtle.digest('SHA-256', data);
  const hashArray = Array.from(new Uint8Array(hashBuffer));
  return '0x' + hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
}

// ── Document builder ──────────────────────────────────────────────────────────

export async function buildDeclarationDocument(
  p: AuthorshipDeclarationParams,
): Promise<AuthorshipDeclarationDocument> {
  const timestamp = Date.now();
  const text = buildDeclarationText(p, timestamp);
  const textHash = await hashText(text);
  return { text, textHash, params: p, timestamp, version: DECLARATION_VERSION };
}

// ── EIP-712 message builder ───────────────────────────────────────────────────

export function buildEIP712AuthorshipMessage(doc: AuthorshipDeclarationDocument) {
  return {
    authorWallet:    doc.params.authorWallet as `0x${string}`,
    safeAddress:     doc.params.safeAddress as `0x${string}`,
    agentTokenId:    BigInt(doc.params.agentTokenId),
    declarationHash: doc.textHash as `0x${string}`,
    timestamp:       BigInt(doc.timestamp),
  };
}

// ── IPFS pin via Lighthouse ───────────────────────────────────────────────────

export async function pinDeclarationToIPFS(
  doc: AuthorshipDeclarationDocument,
  signature: string,
): Promise<string> {
  const payload = {
    version: doc.version,
    agentName: doc.params.agentName,
    domain: doc.params.domain,
    agentTokenId: doc.params.agentTokenId,
    authorWallet: doc.params.authorWallet,
    safeAddress: doc.params.safeAddress,
    timestamp: doc.timestamp,
    declarationText: doc.text,
    textHash: doc.textHash,
    eip712Signature: signature,
    eip712Domain: AUTHORSHIP_EIP712_DOMAIN,
    eip712Types: AUTHORSHIP_EIP712_TYPES,
    jurisdiction: 'Victoria, Australia',
    governingLaw: 'Electronic Transactions (Victoria) Act 2000 (Vic) s.9; Copyright Act 1968 (Cth)',
  };

  const blob = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
  const form = new FormData();
  form.append(
    'file',
    blob,
    `authorship-declaration-${doc.params.agentName}-${doc.timestamp}.json`,
  );

  const apiKey = process.env.LIGHTHOUSE_API_KEY;
  if (!apiKey) throw new Error('LIGHTHOUSE_API_KEY not set');

  const res = await fetch('https://node.lighthouse.storage/api/v0/add', {
    method: 'POST',
    headers: { Authorization: `Bearer ${apiKey}` },
    body: form,
  });

  if (!res.ok) throw new Error(`Lighthouse pin failed: ${res.status}`);
  const data = await res.json() as { Hash: string };
  return `ipfs://${data.Hash}`;
}

// ── GlassBox log ──────────────────────────────────────────────────────────────

const BASE = typeof window !== 'undefined' ? '' : (process.env.NEXTJS_BASE_URL ?? 'https://ghostagent.ninja');

export async function logDeclarationToGlassBox(opts: {
  agentName: string;
  tld: string;
  authorWallet: string;
  textHash: string;
  ipfsCid: string;
  signature: string;
}): Promise<void> {
  const contentHash = await hashText(opts.signature + opts.ipfsCid);
  await fetch(`${BASE}/api/glassbox/log`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      agentName: opts.agentName,
      tld: opts.tld,
      eventType: 'molt-transition',
      contentHash,
      xmtpEnabled: false,
      enhancedLogging: true,
      walletAddress: opts.authorWallet,
      subject: `IP Authorship Declaration signed — ${opts.agentName} (Victorian jurisdiction)`,
      protocol: 'email' as const,
      from: opts.authorWallet,
      to: 'ip-registry',
    }),
  });
}
